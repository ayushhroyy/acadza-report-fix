#!/usr/bin/env python3
"""
Run the engine:

    python3 engine/run.py                # offline replay (committed analysis) → results.json
    python3 engine/run.py --live         # live LLM (set LLM_API_KEY, LLM_BASE_URL, LLM_MODEL)
    python3 engine/run.py --export       # also regenerate console/data.js for the faculty console

Exit code is non-zero if any invariant fails (counts, edit anchors, taxonomy keys).
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from pipeline import run, load_json, ROOT  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--live", action="store_true", help="call the LLM endpoint instead of replaying analysis/")
    ap.add_argument("--export", action="store_true", help="also write console/data.js")
    args = ap.parse_args()

    rows, cases = run(live=args.live)

    taxonomy = load_json(os.path.join(ROOT, "data", "taxonomy.json"))
    verdicts, repairs = set(taxonomy["verdicts"]), set(taxonomy["repairs"])

    # ---- invariants (the "it runs" guarantee) ----
    assert len(rows) == 44, f"expected 44 report rows, got {len(rows)}"
    assert len({r['reportId'] for r in rows}) == 44, "duplicate reportIds"
    for r in rows:
        assert r["verdict"] in verdicts, f"unknown verdict {r['verdict']} in {r['reportId']}"
        assert r["repair"] is None or r["repair"] in repairs, f"unknown repair in {r['reportId']}"
        assert r["route"] in ("auto_apply", "faculty_review", "no_change")
        assert 0.0 <= r["confidence"] <= 1.0
        assert r["student_reply"], f"empty reply for {r['reportId']}"
    # duplicate reports of one question must never disagree
    by_report = {}
    for r in rows:
        key = r["questionId"]
        sig = (r["verdict"], r["repair"], r["route"])
        by_report.setdefault(key, set()).add(sig)
    assert all(len(s) == 1 for s in by_report.values()), "inconsistent verdicts for duplicate reports"
    # every auto_apply row must carry a validated edit
    for r in rows:
        if r["route"] == "auto_apply":
            assert r["edit"], f"{r['reportId']} routed auto_apply without an edit"

    with open(os.path.join(ROOT, "results.json"), "w") as f:
        json.dump(rows, f, indent=1, ensure_ascii=False)

    n = {"defect": 0, "no_error": 0, "other": 0}
    routes = {"auto_apply": 0, "faculty_review": 0, "no_change": 0}
    for r in rows:
        n["defect" if r["verdict"] == "defect" else "no_error" if r["verdict"] == "no_error" else "other"] += 1
        routes[r["route"]] += 1
    print(f"results.json: 44 reports | verdicts {n} | routes {routes}")

    if args.export:
        export_console(cases)


def export_console(cases):
    """Bundle everything the static console needs into console/data.js."""
    bonus = load_json(os.path.join(ROOT, "engine", "analysis", "bonus_findings.json"))
    payload = {
        "cases": [{
            "questionId": c["questionId"],
            "question": c["question"],
            "reports": c["reports"],
            "findings": c["findings"],
            "solver": c["solver"],
            "decision": {k: c["decision"][k] for k in
                         ("verdict", "repair", "confidence", "evidence", "triage_note", "force_route")},
            "edit": c["edit"],
            "edit_fail_reason": c["edit_fail_reason"],
            "route": c["route"],
            "routeReason": c["route_reason"],
            "urgency": c["urgency"],
        } for c in cases],
        "bonus": bonus,
    }
    out = os.path.join(ROOT, "console", "data.js")
    with open(out, "w") as f:
        f.write("// generated by engine/run.py --export — do not edit by hand\n")
        f.write("window.ACADZA = ")
        f.write(json.dumps(payload, ensure_ascii=False))
        f.write(";\n")
    print(f"wrote {out} ({len(cases)} cases)")


if __name__ == "__main__":
    main()
